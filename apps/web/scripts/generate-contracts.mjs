// Generates packages/contracts/types.ts and validators.js (+ .d.ts) from the JSON Schema
// that the backend writes to packages/contracts/schemas/. Ajv runs here, at build time:
// the output is plain ESM without require and without ajv at runtime (CSP has no eval).
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { build } from "esbuild";
import { compile } from "json-schema-to-typescript";

const contracts = fileURLToPath(new URL("../../../packages/contracts/", import.meta.url));
const HEADER = "// Generated by apps/web/scripts/generate-contracts.mjs. Do not edit.\n";

const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

/** Pydantic titles every property; json-schema-to-typescript would make each a named type. */
function stripTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripTitles);
  if (node && typeof node === "object") {
    delete node.title;
    Object.values(node).forEach(stripTitles);
  }
}

/** In discriminated unions Ajv wants discriminator without mapping. */
function stripMappings(node) {
  if (Array.isArray(node)) return node.forEach(stripMappings);
  if (node && typeof node === "object") {
    if (node.discriminator?.mapping) delete node.discriminator.mapping;
    Object.values(node).forEach(stripMappings);
  }
}

const files = (await readdir(join(contracts, "schemas"))).filter((f) => f.endsWith(".schema.json")).sort();
const schemas = [];
for (const file of files) {
  const name = file.replace(".schema.json", "");
  const schema = JSON.parse(await readFile(join(contracts, "schemas", file), "utf8"));
  stripMappings(schema);
  schemas.push({ name, type: schema.title ?? pascal(name), schema });
}

// Types: one document with every model in $defs, so shared models are declared once.
const defs = {};
for (const { type, schema } of schemas) {
  const { $defs = {}, $schema, ...root } = structuredClone(schema);
  void $schema;
  Object.assign(defs, $defs, { [type]: root });
}
stripTitles(defs);
const types = await compile(
  { title: "Contracts", type: "object", additionalProperties: false, $defs: defs },
  "Contracts",
  { bannerComment: "", unreachableDefinitions: true, additionalProperties: false, format: true },
);
await writeFile(join(contracts, "types.ts"), HEADER + types.replace(/^export interface Contracts \{\}\n\n?/m, ""));

// Validators: Ajv standalone, then esbuild inlines Ajv's small runtime helpers.
// messages: false keeps error texts out of the bundle; the app only needs pass or fail.
const ajv = new Ajv2020({
  code: { source: true, esm: true, optimize: true },
  discriminator: true,
  allErrors: false,
  messages: false,
});
addFormats(ajv, ["date-time"]);
for (const { name, type, schema } of schemas) {
  void type;
  ajv.addSchema({ ...schema, $id: name });
}
const work = await mkdtemp(join(tmpdir(), "cycleops-contracts-"));
try {
  const entry = join(work, "validators.mjs");
  // Leaf modules keep validators used only by the API/SSE out of the initial chunk.
  // The barrel preserves the public exports; each leaf retains its own pure factory.
  const directory = join(contracts, "validators");
  await mkdir(directory, { recursive: true });
  for (const file of await readdir(directory)) {
    if (file.endsWith(".js")) await rm(join(directory, file));
  }
  const validators = [];
  for (const { name, type } of schemas) {
    const exported = `validate${type}`;
    await writeFile(entry, standaloneCode(ajv, { [exported]: name }));
    const result = await build({
      entryPoints: [entry],
      bundle: true,
      format: "iife",
      globalName: "contract",
      platform: "neutral",
      nodePaths: [fileURLToPath(new URL("../node_modules", import.meta.url))],
      write: false,
      minify: true,
      legalComments: "none",
    });
    await writeFile(join(directory, `${name}.js`), HEADER + `export const ${exported} = /*#__PURE__*/ (() => {${result.outputFiles[0].text}return contract.${exported};})();\n`);
    validators.push(`export { ${exported} } from "./validators/${name}.js";\n`);
  }
  await writeFile(join(contracts, "validators.js"), HEADER + validators.join(""));
} finally {
  await rm(work, { recursive: true, force: true });
}
const declarations = [
  HEADER,
  `import type { ${schemas.map((s) => s.type).join(", ")} } from "./types";\n\n`,
  "export interface Validator<T> {\n  (data: unknown): data is T;\n  errors?: unknown[] | null;\n}\n\n",
  ...schemas.map((s) => `export declare const validate${s.type}: Validator<${s.type}>;\n`),
].join("");
await writeFile(join(contracts, "validators.d.ts"), declarations);
console.log(`generated types.ts and validators.js for ${schemas.length} schemas`);
